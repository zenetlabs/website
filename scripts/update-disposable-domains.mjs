// Regenerates src/server/disposable-domains.generated.ts from the CC0 list at
// github.com/disposable-email-domains/disposable-email-domains, pinned to one
// commit. Usage: pnpm disposable:update [<commit>]. No runtime dependency: the
// list is vendored and read only by the booking request path.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO = 'disposable-email-domains/disposable-email-domains';
const FILE = 'disposable_email_blocklist.conf';
const PINNED = 'a72c0cecfcdd940d666265e44c0f661282e2d4aa';
const OUT = fileURLToPath(
  new URL('../src/server/disposable-domains.generated.ts', import.meta.url),
);

// Domains we accept even if upstream lists them. Empty to start.
const ALLOW = new Set([]);

const DOMAIN = /^[a-z0-9.-]+\.[a-z0-9-]+$/;

const commit = process.argv[2] ?? PINNED;
if (!/^[0-9a-f]{40}$/.test(commit)) {
  console.error('Usage: pnpm disposable:update [<40-character commit sha>]');
  process.exit(1);
}

const url = `https://raw.githubusercontent.com/${REPO}/${commit}/${FILE}`;
const response = await fetch(url);
if (!response.ok) {
  console.error(`Fetch failed: HTTP ${response.status} for ${url}`);
  process.exit(1);
}
const domains = [
  ...new Set(
    (await response.text())
      .split('\n')
      .map((line) => line.trim().toLowerCase())
      .filter((line) => line !== '' && !line.startsWith('#')),
  ),
]
  .filter((domain) => DOMAIN.test(domain) && !ALLOW.has(domain))
  .sort();

if (domains.length < 5_000) {
  console.error(`Only ${domains.length} domains; refusing to write.`);
  process.exit(1);
}

const date = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUT,
  `// Generated by scripts/update-disposable-domains.mjs; do not edit by hand.
// Source: https://github.com/${REPO} (${FILE}), CC0 1.0.
// Commit ${commit}, fetched ${date}: ${domains.length} domains.
export const DISPOSABLE_DOMAINS = \`${domains.join('\n')}\`;
`,
);
console.log(`Wrote ${domains.length} domains from ${commit.slice(0, 12)}.`);
