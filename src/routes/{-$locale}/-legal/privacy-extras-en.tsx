export function AssistantSection() {
  if (!__ASSISTANT__) return null;
  return (
    <LegalSection title="The site assistant">
      <p>
        Our site has an AI assistant. Before you write to it, it tells you that
        it is an AI system and not a person (Article 50 of the EU AI Act,
        Regulation (EU) 2024/1689). When you use it, we process your messages,
        its replies, the page you were on and the time, to answer you and to
        prevent abuse of the service.
      </p>
      <p>
        The replies are written automatically by an AI model running on
        Cloudflare Workers AI. Cloudflare does not use this content to train
        models. We keep the conversations in our database in the European Union,
        and we do not store your IP address with them.
      </p>
      <p>
        If you book a call from the assistant, the booking form in the chat asks
        for your name and email; they are used for the booking, not sent to the
        AI model. The call is booked only when you then confirm it from the link
        in the email we send you.
      </p>
      <p>
        To limit abuse we also count how many questions each connection asks in
        a day. For that we keep a keyed one-way fingerprint of your IP address:
        it cannot be turned back into the address and it is not linked to your
        conversation. Each day's fingerprint is deleted at 03:00 UTC two days
        later, so it is kept for about 51 hours at most.
      </p>
      <p>
        The assistant can make mistakes. Prices and dates come only from our
        published information, and a person reads every booking and enquiry.
        Please do not share passwords, health information or other sensitive
        data in the chat.
      </p>
    </LegalSection>
  );
}

export function VoiceSection() {
  if (!__VOICE__) return null;
  return (
    <LegalSection title="Voice calls">
      <p>
        Before a voice call with the assistant starts, we tell you that you will
        be talking to an AI system and that the voice you hear is generated by
        AI (Article 50 of the EU AI Act, Regulation (EU) 2024/1689).
      </p>
      <p>
        During the call, the audio from your microphone is streamed to
        ElevenLabs (ElevenLabs Inc., United States), our voice provider, which
        transcribes it, generates the assistant's replies with an AI model it
        hosts, and speaks them. We don't record audio, and we have set
        ElevenLabs not to keep recordings. ElevenLabs keeps the text of the
        conversation for 30 days, then deletes it.
      </p>
      <p>
        We keep a technical record of the call (when it started, its language,
        your time zone and the page, with no audio and no text) for 30 days to
        prevent abuse. If you ask for a call during the conversation, we email
        you a link and the call is booked only when you confirm it there; your
        name, email, company and topic are then stored with your enquiry, as for
        any booking, together with the identifiers of the call (our record's id
        and ElevenLabs' conversation id). We don't use your voice to identify
        you.
      </p>
    </LegalSection>
  );
}

